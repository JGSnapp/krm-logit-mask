from krm_mask.mipt_catalog import _code


def test_mipt_codes_are_parsed_from_competency_and_indicator_cells():
    assert _code("ИП-1. Способен проверять работоспособность") == (
        "ИП-1", "Способен проверять работоспособность")
    assert _code("ППК-Р1.4. Разрабатывает программный код") == (
        "ППК-Р1.4", "Разрабатывает программный код")
    assert _code("ППК-ДА2.1. – Очищает, нормализует данные") == (
        "ППК-ДА2.1", "Очищает, нормализует данные")
    assert _code("УНК-01. Способен применять коммуникационные компетенции")[0] == "УНК-01"
    assert _code("Профессиональные базовые компетенции") is None
